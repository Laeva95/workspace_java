// 패키지 선언문
// MathTool 클래스가 속한 패키지를 명시함
package com.company.tools;

// public 접근제어자를 적용해야 외부 패키지에서 접근할 수 있음
public class MathTool {
	// 두 정수를 더해서 결과 값을 반환하는 메서드
	public int add(int a, int b) {
		return a + b;
	}
	
	// 두 정수를 곱해서 결과 값을 반환하는 메서드
	public int multiply(int a, int b) {
		return a * b;
	}
	
}
