
public class For02 {

	public static void main(String[] args) {
		// for 반복문
		
		// 1. 반복문을 제어할 i 변수 선언
		int i;
		
		// 2. for문을 사용해서 i = 1부터 4가 될때까지 1씩 증가하여 i값 출력
		for (i = 1; i <= 4 ; i++) {
			// i가 4가 될때까지 i값 출력
			System.out.println(i);
		}
		
		System.out.println("---------------------------->>" + i);
		
	}
}
