
public class while01 {
	public static void main(String[] args) {
		// 1부터 5까지의 자연수 반복해서 출력하기
		int i = 1;
		
		while (i <= 5) {
			System.out.print(" " + i);
			
			i++;
		}
		
		System.out.println("\n----------------------");
		
		for(int j = 1; j <= 5; j++) {
			System.out.print(" " + j);
		}
		
		
	}
}
