
public class Opr01 {

	public static void main(String[] args) {
		int a = 10, b = 4, c;
		
		c = a + b;
		
		System.out.println(a + " + " + b + " = " + c);	// 출력: 10 + 4 = 14
		
		c = a - b;
		
		System.out.println(a + " - " + b + " = " + c);	// 출력: 10 - 4 = 6
		
		c = a * b;
		
		System.out.println(a + " X " + b + " = " + c);	// 출력: 10 * 4 = 40
		
		c = a / b;
		
		System.out.println(a + " / " + b + " = " + c);	// 출력: 10 / 4 = 2(2.5에서 버림 처리)
		
		c = a % b;
		
		System.out.println(a + " % " + b + " = " + c);	// 출력: 10 % 4 = 2(나눈 나머지 2)
		
		
		
		
		
	}
}
